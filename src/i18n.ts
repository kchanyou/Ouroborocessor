export const messages: Record<Locale, Messages> = { ko, en, es, ja, zh };

export const localeOptions: Array<{ code: Locale; label: string }> = [
  { code: "ko", label: "한국어" },
  { code: "en", label: "English" },
  { code: "es", label: "Español" },
  { code: "ja", label: "日本語" },
  { code: "zh", label: "简体中文" },
];

export function detectLocale(language = navigator.language): Locale {
  const prefix = language.toLowerCase().split("-")[0];
  return localeOptions.some((option) => option.code === prefix)
    ? (prefix as Locale)
    : "en";
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {},
) {
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    messages[locale][key],
  );
}
